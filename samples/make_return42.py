#!/usr/bin/env python3
"""Build our own deterministic no-import AMD64 PE diagnostic, without a linker.

Its entry point follows the probe's uint32_t (*)() contract: mov eax,42; ret.
It has no CRT, OS imports, relocations, TLS or exception handlers. It is NOT a
normal double-clickable Windows console program or evidence of game support.
"""

import argparse
from pathlib import Path
import struct


def make_fixture() -> bytes:
    image = bytearray(1024)
    struct.pack_into("<H", image, 0, 0x5A4D)
    struct.pack_into("<I", image, 0x3C, 0x80)
    image[0x80:0x84] = b"PE\0\0"
    struct.pack_into("<HHIIIHH", image, 0x84, 0x8664, 1, 0, 0, 0, 240, 0x23)
    optional = 0x98
    struct.pack_into("<H", image, optional, 0x20B)
    struct.pack_into("<I", image, optional + 4, 512)  # SizeOfCode
    struct.pack_into("<IIQ", image, optional + 16, 0x1000, 0x1000, 0x140000000)
    struct.pack_into("<II", image, optional + 32, 4096, 512)
    struct.pack_into("<HH", image, optional + 40, 6, 0)
    struct.pack_into("<HH", image, optional + 48, 6, 0)
    struct.pack_into("<II", image, optional + 56, 8192, 512)
    struct.pack_into("<HH", image, optional + 68, 3, 0x100)  # CUI, NX compatible
    struct.pack_into("<QQQQ", image, optional + 72, 0x100000, 0x1000, 0x100000, 0x1000)
    struct.pack_into("<I", image, optional + 108, 16)
    section = optional + 240
    image[section:section + 8] = b".text\0\0\0"
    struct.pack_into("<IIII", image, section + 8, 6, 0x1000, 512, 512)
    struct.pack_into("<I", image, section + 36, 0x60000020)
    image[512:518] = b"\xb8\x2a\x00\x00\x00\xc3"
    return bytes(image)


def cpp_source(data: bytes) -> str:
    lines = [
        '// Generated by samples/make_return42.py. Self-authored diagnostic bytes.',
        '#include "Return42Fixture.h"',
        '',
        'namespace xcdm::samples {',
        'const std::array<std::uint8_t, 1024>& Return42PeBytes() noexcept {',
        '    static constexpr std::array<std::uint8_t, 1024> bytes = {{',
    ]
    for start in range(0, len(data), 16):
        lines.append('        ' + ', '.join(f'0x{value:02x}' for value in data[start:start + 16]) + ',')
    lines.extend(['    }};', '    return bytes;', '}', '} // namespace xcdm::samples', ''])
    return '\n'.join(lines)


def main() -> None:
    directory = Path(__file__).resolve().parent
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, default=directory / 'return42.exe')
    parser.add_argument('--cpp-output', type=Path, default=None)
    args = parser.parse_args()
    fixture = make_fixture()
    args.output.write_bytes(fixture)
    if args.cpp_output:
        args.cpp_output.write_text(cpp_source(fixture), encoding='utf-8')
    print(f'Wrote {len(fixture)} diagnostic bytes to {args.output}')


if __name__ == '__main__':
    main()
